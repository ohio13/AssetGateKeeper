#!/usr/bin/env python3
r"""Live demo: drop assets into a watch folder one at a time, on a timer.

Run the server and the gate, then run this, then open the dashboard. Each step
prints what it is about to export, waits a beat, and writes the file — which is
exactly the event stream a DCC's "export" button produces.

    # terminal 1
    python server/asset_health_server.py --port 8090 --db scratch/live/demo.db

    # terminal 2
    python asset_gatekeeper.py scratch/live/watch --auto-heal \
        --telemetry-url http://127.0.0.1:8090/api/telemetry

    # terminal 3
    python demo/live_demo.py scratch/live/watch --delay 7

    # browser
    http://127.0.0.1:8090/dashboard?refresh=5

The assets are deliberately boring and deterministic: two that pass, and a
sequence that breaks one rule at a time so you can watch each counter move.
"""

