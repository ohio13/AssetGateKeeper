def steps(watch: Path) -> list[tuple[str, str, object]]:
    """(description, filename, writer) in the order a demo wants to watch them."""
    return [
        ("a clean crate — should PASS", "crate_01.obj",
         lambda p: write_obj(p, 12, 1)),
        ("a hero statue, 72,500 tris / 4 materials — should FAIL twice",
         "hero_statue.gltf", lambda p: write_gltf(p, 72_500, 4)),
        ("a 1024x1024 albedo with the right suffix — should PASS", "stone_Albedo.png",
         lambda p: write_png(p, (1024, 1024), 3)),
        ("a 300x300 icon named badly — should FAIL twice (NPOT + naming)", "ui_icon.png",
         lambda p: write_png(p, (300, 300), 7)),
        ("a 4096x1024 hull — should FAIL on resolution only", "hull_Albedo.png",
         lambda p: write_png(p, (4096, 1024), 11)),
        ("a 4,000-tri mesh with 4 materials — should FAIL on slots only",
         "crate_4mtl.obj", lambda p: write_obj(p, 4_000, 4)),
        ("a 1000x1000 unnamed texture — FAILS raw, HEALS if --auto-heal is on",
         "stone_texture.png", lambda p: write_png(p, (1000, 1000), 17)),
        ("a JPEG wearing a .png extension — should FAIL as mislabeled", "fake_Albedo.png",
         lambda p: _write_jpeg(p)),
        ("the fixed crate, back under budget — should PASS", "crate_02.obj",
         lambda p: write_obj(p, 12, 1)),
    ]


def _write_jpeg(path: Path) -> None:
    Image.new("RGB", (256, 256), (120, 60, 60)).save(path, format="JPEG")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="live_demo.py",
        description="Produce assets one at a time so a running dashboard can be watched.")
    parser.add_argument("watch", nargs="?", default="scratch/live/watch",
                        help="folder the gatekeeper is watching")
    parser.add_argument("--delay", type=float, default=7.0,
                        help="seconds between exports (default 7)")
    parser.add_argument("--reset", action="store_true",
                        help="empty the watch folder first")
    parser.add_argument("--only", metavar="N", help="run a single step by number (1-based)")
    options = parser.parse_args(argv)

    watch = Path(options.watch)
    watch.mkdir(parents=True, exist_ok=True)
    if options.reset:
        for item in watch.iterdir():
            if item.name.startswith("."):
                continue
            shutil.rmtree(item) if item.is_dir() else item.unlink()

    plan = steps(watch)
    if options.only:
        try:
            chosen = [plan[int(options.only) - 1]]
        except (ValueError, IndexError):
            print(f"no step {options.only}; there are {len(plan)}", file=sys.stderr)
            return 2
    else:
        chosen = plan

    print(f"watch folder: {watch.resolve()}")
    print(f"steps: {len(chosen)}, {options.delay:g}s apart\n")
    for index, (description, filename, writer) in enumerate(chosen, start=1):
        print(f"[{index}/{len(chosen)}] {description}")
        print(f"          writing {filename} ...", flush=True)
        target = watch / filename
        try:
            writer(target)                      # type: ignore[operator]
        except Exception as exc:                # a demo must not die mid-show
            print(f"          failed to write: {exc}", file=sys.stderr)
        else:
            print(f"          wrote {target.stat().st_size:,} bytes", flush=True)
        if index < len(chosen):
            time.sleep(options.delay)
    print("\ndone. Open http://127.0.0.1:8090/dashboard?refresh=5 to see it.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
