def write_obj(path: Path, triangles: int, materials: int) -> None:
    """A trivial OBJ: a fan of quads split into triangles, N material groups."""
    per_group = max(1, triangles // materials)
    lines = ["# generated by demo/live_demo.py"]
    for index in range(materials):
        lines.append(f"newmtl material_{index}")
        lines.append(f"Kd 0.7 {0.3 + index * 0.1:.2f} 0.2")
        lines.append(f"usemtl material_{index}")
        for step in range(per_group):
            x = step * 0.01
            lines.append(f"v {x:.3f} 0.000 0.000")
            lines.append(f"v {x:.3f} 0.010 0.000")
            lines.append(f"v {x + 0.01:.3f} 0.010 0.000")
            base = index * per_group * 3 + step * 3
            lines.append(f"f {base + 1} {base + 2} {base + 3}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_gltf(path: Path, triangles: int, materials: int) -> None:
    """A real glTF: one primitive per material, embedded base64 buffer.

    Deliberately built the way a DCC exports (separate primitives per material)
    because that is what makes single-file material counting worth trusting.
    """
    cols = max(2, int(math.isqrt(max(1, triangles // 2))) + 1)
    rows = max(1, math.ceil(triangles / 2 / cols))
    positions: list[float] = []
    for y in range(rows + 1):
        for x in range(cols + 1):
            positions += [x / cols, y / rows, 0.0]

    quads: list[int] = []
    for y in range(rows):
        for x in range(cols):
            base = y * (cols + 1) + x
            quads += [base, base + 1, base + cols + 1,
                      base + 1, base + cols + 2, base + cols + 1]
    quads = quads[: triangles * 3]
    while len(quads) < triangles * 3:      # tiny meshes: pad with degenerate-free reuse
        quads += quads[:3]

    # glTF quirk worth knowing: primitive.indices is an *accessor index*, not an
    # inline descriptor. One index accessor per material group.
    chunk = max(3, (len(quads) // materials) // 3 * 3)
    primitives = []
    index_accessors = []
    offset = 0
    for index in range(materials):
        end = len(quads) if index == materials - 1 else min(len(quads), offset + chunk)
        if end <= offset:
            break
        index_accessors.append({
            "bufferView": 1, "byteOffset": offset * 4, "componentType": 5125,
            "count": end - offset, "type": "SCALAR",
        })
        primitives.append({
            "attributes": {"POSITION": 0},
            "indices": len(index_accessors),      # accessor 0 is POSITION
            "material": index,
        })
        offset = end

    position_bytes = struct.pack(f"<{len(positions)}f", *positions)
    index_bytes = struct.pack(f"<{len(quads)}I", *quads)
    blob = position_bytes + index_bytes
    xs = positions[0::3]
    ys = positions[1::3]
    document = {
        "asset": {"version": "2.0", "generator": "demo/live_demo.py"},
        "scene": 0,
        "scenes": [{"nodes": [0]}],
        "nodes": [{"mesh": 0, "name": path.stem}],
        "meshes": [{"name": path.stem, "primitives": primitives}],
        "materials": [{"name": f"material_{i}", "pbrMetallicRoughness": {
            "baseColorFactor": [0.6, 0.4 + i * 0.05, 0.3, 1.0]}} for i in range(materials)],
        "buffers": [{"byteLength": len(blob),
                     "uri": "data:application/octet-stream;base64,"
                            + base64.b64encode(blob).decode("ascii")}],
        "bufferViews": [
            {"buffer": 0, "byteOffset": 0, "byteLength": len(position_bytes), "target": 34962},
            {"buffer": 0, "byteOffset": len(position_bytes), "byteLength": len(index_bytes),
             "target": 34963},
        ],
        "accessors": [
            {"bufferView": 0, "componentType": 5126, "count": len(positions) // 3,
             "type": "VEC3", "min": [min(xs), min(ys), 0.0], "max": [max(xs), max(ys), 0.0]},
            *index_accessors,
        ],
    }
    path.write_text(json.dumps(document, indent=1), encoding="utf-8")


def write_png(path: Path, size: tuple[int, int], seed: int = 0) -> None:
    """A plaid-ish texture so the image is obviously not a blank canvas."""
    width, height = size
    image = Image.new("RGB", size)
    pixels = image.load()
    for y in range(height):
        for x in range(width):
            pixels[x, y] = (90 + (x * 7 + seed) % 80, 70 + (y * 5) % 70, 60 + ((x ^ y) % 60))
    image.save(path)


